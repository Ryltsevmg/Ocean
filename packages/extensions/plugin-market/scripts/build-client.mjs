/**
 * Build the browser bundle: the module sources are inlined into one
 * `window.__ModuleLoader__` factory because the loader resolves no relative
 * imports. `client.js` is generated, committed, and checked fresh by
 * `tests/client-bundle.test.mjs`; edit `catalog.js` or `src/*.js` instead.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Package root, one level above this script. */
export const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)))

/** Sources in dependency order; earlier ones declare what later ones read. */
export const MODULES = ['src/catalog.js', 'src/view.js', 'src/controller.js', 'src/locales.js', 'src/ui.js', 'src/entry.js']

/** Header of the generated file. */
const HEADER = `/** GENERATED by scripts/build-client.mjs from catalog.js and src/*.js — do not edit. */
window.__ModuleLoader__.load({
  id: '@ocean/ocean-plugin-market',
  factory(require) {
    const React = require('react')
    const primitives = require('@ocean/ocean-client-ui-primitives')
`

/** Footer closing the loader call. */
const FOOTER = `
    return createMarket(React, primitives)
  },
})
`

/**
 * One module's text with its top-level `export ` keywords removed, so the
 * concatenation stays a single factory body.
 * @param {string} source module text.
 * @returns {string} the same text without top-level exports.
 */
export function stripExports(source) {
  return source.split('\n').filter(line => !line.startsWith('import ')).map(line => line.startsWith('export ') ? line.slice('export '.length) : line).join('\n')
}

/**
 * Render the complete browser bundle.
 * @returns {Promise<string>} the `client.js` text.
 */
export async function renderClientBundle() {
  const parts = []
  for (const module of MODULES) {
    const source = await readFile(join(PACKAGE_ROOT, module), 'utf8')
    parts.push(`    // ---- ${module} ----\n${stripExports(source).trimEnd()}\n`)
  }
  return `${HEADER}\n${parts.join('\n')}${FOOTER}`
}

/**
 * Write `client.js`, or check the committed copy when `check` is true.
 * @param {{ check?: boolean }} [options] `check` compares instead of writing.
 * @returns {Promise<{ path: string, stale: boolean }>} the target and whether a committed copy differs.
 */
export async function buildClient(options = {}) {
  const path = join(PACKAGE_ROOT, 'client.js')
  const rendered = await renderClientBundle()
  if (options.check === true) {
    const committed = await readFile(path, 'utf8')
    return { path, stale: committed !== rendered }
  }
  await writeFile(path, rendered, 'utf8')
  return { path, stale: false }
}

// A direct run regenerates the file; importing this module never writes.
if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { path } = await buildClient()
  process.stdout.write(`wrote ${path}\n`)
}
